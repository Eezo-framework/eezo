package io.eezo.sbt

import java.nio.charset.StandardCharsets
import java.nio.file.Files

/** The pure half of the generator that writes `io.eezo.generated.ConfigFile`: the unit's text, the
  * digest in it, and the path literal. The task that writes it needs a live build, and the plugin
  * is a 2.12 cross build no Scala 3 module can compile the text with, so the text is pinned here
  * and `config`'s CheckedSuite compiles the call it holds.
  */
class ConfigFileSuite extends munit.FunSuite {

  test("the unit extends the generated root and checks the named class against the file") {
    assertNoDiff(
      ConfigFile.render("shop.ShopConfig", "/srv/shop/src/main/resources/application.conf", "ab12"),
      """|// AUTO-GENERATED by eezo from src/main/resources/application.conf and the files beside it (digest ab12). Do not edit.
         |package io.eezo.generated
         |
         |object ConfigFile extends io.eezo.config.Config.Root.Generated {
         |  val root: io.eezo.config.Config.Root[shop.ShopConfig] =
         |    io.eezo.config.Config.checked[shop.ShopConfig]("/srv/shop/src/main/resources/application.conf")
         |}
         |""".stripMargin
    )
  }

  test("a Windows path is escaped, so the literal names the file it was given") {
    val text =
      ConfigFile.render("ShopConfig", "C:\\shop\\src\\main\\resources\\application.conf", "0")
    assert(
      text.contains("(\"C:\\\\shop\\\\src\\\\main\\\\resources\\\\application.conf\")"),
      text
    )
  }

  test("the digest moves with the file's bytes, and an absent file has one of its own") {
    val dir  = Files.createTempDirectory("eezo-config-file")
    val file = dir.resolve("application.conf").toFile
    assertEquals(ConfigFile.digest(file), "absent")
    Files.write(file.toPath, "port = 8080\n".getBytes(StandardCharsets.UTF_8))
    val first = ConfigFile.digest(file)
    assertEquals(first.length, 64)
    Files.write(file.toPath, "port = 8081\n".getBytes(StandardCharsets.UTF_8))
    assertNotEquals(ConfigFile.digest(file), first)
  }

  test("the digest moves with a file the conf includes, nested or beside it, and only with those") {
    val dir                                       = Files.createTempDirectory("eezo-config-include")
    val conf                                      = dir.resolve("application.conf").toFile
    def put(relative: String, text: String): Unit = {
      val file = dir.resolve(relative)
      Files.createDirectories(file.getParent): Unit
      Files.write(file, text.getBytes(StandardCharsets.UTF_8)): Unit
    }
    put("application.conf", "include \"secrets.conf\"\ninclude \"db/pool.conf\"\n")
    put("secrets.conf", "port = 8080\n")
    put("db/pool.conf", "size = 4\n")
    put("logback.xml", "<configuration/>\n")
    val first = ConfigFile.digest(conf)

    put("secrets.conf", "port = 8081\n")
    val second = ConfigFile.digest(conf)
    assertNotEquals(second, first)

    put("db/pool.conf", "size = 8\n")
    val third = ConfigFile.digest(conf)
    assertNotEquals(third, second)

    put("logback.xml", "<configuration debug=\"true\"/>\n")
    assertEquals(ConfigFile.digest(conf), third)
  }

  test("the watched globs are the files the digest reads, so an included file restarts the loop") {
    val dir                                = Files.createTempDirectory("eezo-config-watch")
    def watched(relative: String): Boolean =
      ConfigFile.watched(dir.toFile).exists(_.matches(dir.resolve(relative)))
    assert(watched("application.conf"))
    assert(watched("secrets.conf"))
    assert(watched("db/pool.conf"))
    assert(watched("defaults.json"))
    assert(watched("db/pool.properties"))
    assert(!watched("logback.xml"))
  }

  test("a named class writes the unit, and naming none deletes a unit left from before") {
    val dir         = Files.createTempDirectory("eezo-config-unit")
    val conf        = dir.resolve("application.conf").toFile
    val destination = dir.resolve("managed/io/eezo/generated/ConfigFile.scala").toFile
    Files.write(conf.toPath, "port = 8080\n".getBytes(StandardCharsets.UTF_8))

    assertEquals(ConfigFile.write(Some("shop.ShopConfig"), conf, destination), Seq(destination))
    val text = new String(Files.readAllBytes(destination.toPath), StandardCharsets.UTF_8)
    assertEquals(
      text,
      ConfigFile.render("shop.ShopConfig", conf.getAbsolutePath, ConfigFile.digest(conf))
    )

    assertEquals(ConfigFile.write(None, conf, destination), Seq.empty)
    assert(!destination.exists)
    assertEquals(ConfigFile.write(None, conf, destination), Seq.empty)
  }

  test("an unchanged unit is not written again, so the compile after it has nothing to redo") {
    val dir         = Files.createTempDirectory("eezo-config-unchanged")
    val conf        = dir.resolve("application.conf").toFile
    val destination = dir.resolve("ConfigFile.scala").toFile
    ConfigFile.write(Some("ShopConfig"), conf, destination): Unit
    val stamp = java.nio.file.attribute.FileTime.fromMillis(0L)
    Files.setLastModifiedTime(destination.toPath, stamp): Unit
    ConfigFile.write(Some("ShopConfig"), conf, destination): Unit
    assertEquals(Files.getLastModifiedTime(destination.toPath), stamp)
  }
}
