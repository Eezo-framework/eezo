package io.eezo.sbt

import java.io.File
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.util.Arrays

/** The unit the plugin writes when the build names the class `application.conf` is read into:
  * `io.eezo.generated.ConfigFile`, beside `Routes`, holding the one call that checks the class
  * against the file at compile time.
  *
  * The plugin writes the call rather than the application, so a project names its class once, in
  * the build, and its entry object writes nothing. The incremental compiler never looks inside a
  * macro's expansion, so the unit's own text is what has to change for it to be compiled again: the
  * file's digest is in a comment for an edit to the file alone, and the class is named in the call
  * for an edit to the class alone, which the macro follows into every section.
  */
private[sbt] object ConfigFile {

  /** Writes the unit for `cls`, or deletes it when the build names no class, so a project that
    * drops its class is not left with a unit that names a class it no longer has. Identical bytes
    * are not written again, since a moved timestamp would make the next compile read the unit as
    * changed.
    */
  def write(cls: Option[String], conf: File, destination: File): Seq[File] =
    cls match {
      case None =>
        Files.deleteIfExists(destination.toPath): Unit
        Seq.empty
      case Some(name) =>
        val text = render(name, conf.getAbsolutePath, digest(conf)).getBytes(StandardCharsets.UTF_8)
        if (!destination.isFile || !Arrays.equals(Files.readAllBytes(destination.toPath), text)) {
          Files.createDirectories(destination.toPath.getParent): Unit
          Files.write(destination.toPath, text): Unit
        }
        Seq(destination)
    }

  def render(cls: String, path: String, digest: String): String =
    s"""|// AUTO-GENERATED by eezo from src/main/resources/application.conf (sha-256 $digest). Do not edit.
        |package io.eezo.generated
        |
        |object ConfigFile extends io.eezo.config.Config.Root.Generated {
        |  val root: io.eezo.config.Config.Root[$cls] =
        |    io.eezo.config.Config.checked[$cls](${literal(path)})
        |}
        |""".stripMargin

  /** A Scala string literal for `path`. A Windows path's backslashes would otherwise be read as
    * escapes, and the macro would open a file nobody named.
    */
  private def literal(path: String): String =
    "\"" + path.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

  /** SHA-256 of the file's bytes, or `absent`, so that a file created later changes the unit too.
    */
  def digest(file: File): String =
    if (!file.isFile) "absent" else Tailwind.sha256(file)
}
