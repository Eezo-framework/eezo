package io.eezo.sbt

import java.io.File
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.security.MessageDigest
import java.util.Arrays
import sbt.nio.file.Glob
import sbt.nio.file.RecursiveGlob

/** The unit the plugin writes when the build names the class `application.conf` is read into:
  * `io.eezo.generated.ConfigFile`, beside `Routes`, holding the one call that checks the class
  * against the file at compile time.
  *
  * The plugin writes the call rather than the application, so a project names its class once, in
  * the build, and its entry object writes nothing. The incremental compiler never looks inside a
  * macro's expansion, so the unit's own text is what has to change for it to be compiled again: the
  * digest of the file and the config files beside it is in a comment for an edit to any of them,
  * and the class is named in the call for an edit to the class alone, which the macro follows into
  * every section.
  */
private[sbt] object ConfigFile {

  /** Writes the unit for `cls`, or deletes it when the build names no class, so a project that
    * drops its class is not left with a unit that names a class it no longer has. Identical bytes
    * are not written again, since a moved timestamp would make the next compile read the unit as
    * changed.
    */
  def write(cls: Option[String], conf: File, destination: File): Seq[File] =
    cls match {
      case None =>
        Files.deleteIfExists(destination.toPath): Unit
        Seq.empty
      case Some(name) =>
        val text = render(name, conf.getAbsolutePath, digest(conf)).getBytes(StandardCharsets.UTF_8)
        if (!destination.isFile || !Arrays.equals(Files.readAllBytes(destination.toPath), text)) {
          Files.createDirectories(destination.toPath.getParent): Unit
          Files.write(destination.toPath, text): Unit
        }
        Seq(destination)
    }

  def render(cls: String, path: String, digest: String): String =
    s"""|// AUTO-GENERATED by eezo from src/main/resources/application.conf and the files beside it (digest $digest). Do not edit.
        |package io.eezo.generated
        |
        |object ConfigFile extends io.eezo.config.Config.Root.Generated {
        |  val root: io.eezo.config.Config.Root[$cls] =
        |    io.eezo.config.Config.checked[$cls](${literal(path)})
        |}
        |""".stripMargin

  /** A Scala string literal for `path`. A Windows path's backslashes would otherwise be read as
    * escapes, and the macro would open a file nobody named.
    */
  private def literal(path: String): String =
    "\"" + path.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

  /** SHA-256 over the file and every `.conf`, `.json` and `.properties` file under its directory,
    * or `absent` when the file itself is missing, so that a file created later changes the unit
    * too.
    *
    * The check parses `include`s too, and the incremental compiler sees none of them. Following the
    * directives would need a HOCON parser in the plugin and would miss the ones it cannot resolve,
    * so the whole directory is read instead: an edit to a file the conf includes, which could drop
    * a required field or add a literal secret, then moves the digest as an edit to the conf does.
    * An include outside the directory is not seen.
    */
  def digest(file: File): String =
    if (!file.isFile) "absent"
    else {
      val dir      = file.getParentFile.toPath
      val combined = MessageDigest.getInstance("SHA-256")
      configFiles(dir).foreach { path =>
        val name = dir.relativize(path).toString.replace('\\', '/')
        combined.update(s"$name ${Tailwind.sha256(path.toFile)}\n".getBytes(StandardCharsets.UTF_8))
      }
      combined.digest().map(b => f"$b%02x").mkString
    }

  private val Extensions = Seq(".conf", ".json", ".properties")

  /** The globs the dev loop watches, the same files the digest reads, so that a save of an included
    * file restarts the loop as a save of the conf does. A trigger on the conf alone would leave the
    * check unrun until some other edit.
    */
  def watched(resourceDirectory: File): Seq[Glob] =
    Extensions.map(extension => Glob(resourceDirectory, RecursiveGlob / s"*$extension"))

  private def configFiles(dir: java.nio.file.Path): Seq[java.nio.file.Path] = {
    val walk = Files.walk(dir)
    try
      walk.toArray.toSeq
        .map(_.asInstanceOf[java.nio.file.Path])
        .filter(p => Files.isRegularFile(p) && Extensions.exists(p.getFileName.toString.endsWith))
        .sortBy(dir.relativize(_).toString)
    finally walk.close()
  }
}
